// ⚠️ 생성 파일 — lucide_icons 패키지의 static const IconData 전체에서 생성.
// `_byName` 은 수작업 편집 금지(패키지 버전 변경 시 재생성). `_aliases` 만 수작업.
import 'package:flutter/widgets.dart';
import 'package:lucide_icons_flutter/lucide_icons.dart';

/// 백엔드 카테고리/자산 `icon` 컬럼 (lucide-react kebab 이름) → Flutter `IconData`.
///
/// `_normalize` 가 소문자화 + `-_` 제거로 kebab(`building-2`)을 camel-lower
/// (`building2`)로 맞춰 lookup. `_byName` 은 lucide_icons 패키지 전체에서 생성돼
/// 웹 DynamicIcon 과 동일 universe — 카테고리가 어떤 lucide 아이콘을 써도
/// fallback(tag)로 새지 않는다. 패키지 버전에 아직 없는 이름만 `_aliases` 로 보강.
IconData lucideByName(String? name, {IconData fallback = LucideIcons.tag}) {
  if (name == null || name.isEmpty) return fallback;
  final key = _normalize(name);
  return _byName[key] ?? _aliases[key] ?? fallback;
}

String _normalize(String s) =>
    s.toLowerCase().replaceAll(RegExp(r'[-_\s]'), '');

