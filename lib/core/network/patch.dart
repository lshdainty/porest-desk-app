/// 수정(PUT) 본문의 한 칸을 **어떤 상태로 실을지** 호출부가 고르는 값.
///
/// 서버는 2026-09-07 부터 수정 본문의 세 가지를 서로 다른 뜻으로 읽는다
/// (desk-back `Patch`, QA #96).
///
/// | 본문 | 뜻 |
/// |---|---|
/// | 키가 없다 | 건드리지 마라 |
/// | `"key": null` | 지워라 |
/// | `"key": 값` | 이 값으로 바꿔라 |
///
/// Dart 의 널 인지 맵 엔트리(`'key': ?value`)는 앞의 둘을 하나로 뭉친다 — 값이 null 이면
/// 키째 빠지므로 "지워라" 를 보낼 방법이 아예 없다. 종전엔 서버가 "키 없음" 도 null 로
/// 덮어서 **우연히** 지워졌는데, 서버가 셋을 가르기 시작하자 화면에서 칸을 비우고 저장해도
/// 옛 값이 그대로 남았다(QA 2026-09-08 #99).
///
/// **어느 칸을 비울 수 있는지는 화면만 안다.** 자산 수정은 계좌·카드·투자 세 화면이 한
/// 메서드를 나눠 쓰는데, 카드 화면엔 메모 칸이 없다 — 리포지토리가 일괄로 메모를 null 로
/// 실으면 계좌 화면에서 적어 둔 메모가 카드를 고칠 때마다 사라진다. 그래서 판단을
/// 호출부로 올린다: 화면이 소유한 칸만 [Patch.set] 으로 싣고, 나머지는 기본값
/// [Patch.keep] 이라 키가 아예 빠진다.
///
/// ```dart
/// await repo.update(
///   id: id,
///   memo: Patch.set(memo.isEmpty ? null : memo), // 이 화면이 비울 수 있는 칸
///   // creditLimit 은 안 넘긴다 — 이 화면엔 없는 칸이라 서버가 지금 값을 지킨다
/// );
/// ```
///
/// **왜 빈 문자열이 아니라 null 인가.** 웹은 지금 빈 칸을 `""` 로 보내고 그것도 동작한다.
/// 하지만 `""` 는 "지움" 의 공통 표현이 될 수 없다 — 색은 `#RRGGBB` 형식 검사에 걸려
/// 400 이 되고, 금액·날짜·아이디·enum 칸에는 빈 문자열이라는 값 자체가 없다. 반대로
/// null 은 모든 타입에서 통하고, 서버가 "지움" 으로 이름 붙인 것도 null 이다.
/// 그래서 앱은 null 로 간다. 서버는 `""` 를 정규화하지 않아 DB 에 `''` 로 그대로 남으므로
/// 두 클라이언트가 만든 값이 갈리는데, 그건 웹을 null 로 옮기거나 서버가 빈 문자열을
/// null 로 접어서 맞출 일이다(이 PR 범위 밖).
///
/// 생성(POST)에는 쓰지 않는다. "안 보냄 = 유지" 는 수정에만 있는 뜻이다.
class Patch<T extends Object> {
  /// 키를 싣지 않는다 — 서버가 지금 값을 그대로 둔다.
  const Patch.keep() : present = false, value = null;

  /// 키를 싣는다. [value] 가 null 이면 "지워라" 다.
  const Patch.set(this.value) : present = true;

  /// 본문에 키를 실을 것인가.
  final bool present;

  /// 실을 값. [present] 가 false 면 의미가 없다.
  final T? value;
}
